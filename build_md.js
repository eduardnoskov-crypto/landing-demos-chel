const fs = require('fs');
const lines = fs.readFileSync('лендинг_крюки_100.csv', 'utf8').split(/\r?\n/).slice(1).filter(Boolean);
let md = '# Выборка: малый бизнес Челябинска (2ГИС) — есть email, нет сайта\n\n';
md += '> Критерии отбора: карточка организации в 2ГИС содержит электронную почту и **не содержит сайта**. Шиномонтаж исключён. Сбор: ноябрь 2026, ссылки на карточки рабочие — можно проверить каждую строку.\n\n';
md += '| № | Бизнес | Категория | Телефон | Email | Рейтинг (отзывов) | Крюк | Идея лендинга |\n|---|---|---|---|---|---|---|---|\n';
for (const l of lines) {
  const c = l.split(';').map(s => s.replace(/^"|"$/g, '').replace(/""/g, '"'));
  md += `| ${c[0]} | ${c[1]} | ${c[2]} | ${c[4]} | ${c[5]} | ${c[6]} (${c[7]}) | ${c[8]} | ${c[9]} |\n`;
}
fs.writeFileSync('лендинг_крюки_100.md', md);
console.log('MD written:', lines.length, 'rows');
